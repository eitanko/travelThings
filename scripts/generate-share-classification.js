/**
 * Generates targets/share/Classification.swift from src/domain/classification.ts + types.ts, so the iOS Share extension
 * and the app share ONE taxonomy. Run `npm run generate:share`; the unit test fails if the committed file is stale.
 */
const fs = require('fs');
const path = require('path');
const ts = require('typescript');

const root = path.join(__dirname, '..');
const OUT = path.join(root, 'targets/share/Classification.swift');

// Icon names used by the app → SF Symbols (matches the previous native chips).
const SYMBOL = {
  plane: 'airplane', bed: 'bed.double', bus: 'bus', ticket: 'ticket',
  passport: 'person.text.rectangle', visa: 'checkmark.seal', file: 'doc',
};

function load(file, mods = {}) {
  const src = fs.readFileSync(path.join(root, file), 'utf8');
  const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019 } }).outputText;
  const m = { exports: {} };
  new Function('module', 'exports', 'require', js)(m, m.exports, (n) => mods[n] ?? {});
  return m.exports;
}

function generate() {
  const types = load('src/domain/types.ts');
  const c = load('src/domain/classification.ts', { './types': types });
  const q = (s) => JSON.stringify(s);
  const lines = [];
  const L = (s = '') => lines.push(s);

  L('// GENERATED by scripts/generate-share-classification.js from src/domain/classification.ts — do not edit.');
  L('// Run `npm run generate:share` after changing the taxonomy; a unit test fails if this file is out of date.');
  L('');
  L('enum DocCategory: String, CaseIterable, Identifiable {');
  L(`  case ${types.CATEGORIES.join(', ')}`);
  L('  var id: String { rawValue }');
  const sw = (name, fn) => {
    L(`  var ${name}: String {`);
    L('    switch self {');
    for (const k of types.CATEGORIES) L(`    case .${k}: return ${q(fn(k))}`);
    L('    }');
    L('  }');
  };
  sw('label', (k) => c.CATEGORY_LABEL[k]);
  sw('dateLabel', (k) => c.PRIMARY_DATE_LABEL[k]);
  sw('dateHint', (k) => c.DATE_HINT[k]);
  L('  /// Personal documents store the date as an expiration date; every other category as the event date.');
  L('  var usesExpirationDate: Bool { self == .personal }');
  L('  var types: [DocType] {');
  L('    switch self {');
  for (const k of types.CATEGORIES) L(`    case .${k}: return [${c.CATEGORY_TYPES[k].map((t) => '.' + t).join(', ')}]`);
  L('    }');
  L('  }');
  L('}');
  L('');
  L('enum DocType: String, CaseIterable, Identifiable {');
  L(`  case ${types.DOCUMENT_TYPES.join(', ')}`);
  L('  var id: String { rawValue }');
  const tsw = (name, ret, fn) => {
    L(`  var ${name}: ${ret} {`);
    L('    switch self {');
    for (const k of types.DOCUMENT_TYPES) L(`    case .${k}: return ${fn(k)}`);
    L('    }');
    L('  }');
  };
  tsw('label', 'String', (k) => q(c.TYPE_INFO[k].label));
  tsw('symbol', 'String', (k) => q(SYMBOL[c.TYPE_INFO[k].icon] ?? 'doc'));
  tsw('category', 'DocCategory', (k) => '.' + c.TYPE_INFO[k].category);
  L('}');
  L('');
  L('enum Classification {');
  L(`  static let defaultCategory: DocCategory = .${c.DEFAULT_CATEGORY}`);
  L(`  static let defaultType: DocType = .${c.DEFAULT_TYPE}`);
  L('}');
  L('');
  return lines.join('\n');
}

module.exports = { generate, OUT };
if (require.main === module) {
  fs.writeFileSync(OUT, generate());
  console.log('wrote', path.relative(root, OUT));
}
